export function countryCodeFor(name?: string): string | undefined {
  if (!name) return undefined;
  return NAME_TO_CODE[name.trim().toLowerCase()];
}

export function centroidFor(code?: string): [number, number] | undefined {
  if (!code) return undefined;
  return COUNTRY_CENTROIDS[code.toUpperCase()];
}
